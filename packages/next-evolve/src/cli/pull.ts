// `next-evolve pull` (spec §7.8): fetches and verifies the current signed
// bundle and writes `.evolve/bundle.generated.ts` (gitignored), which the
// proxy imports as its cold-start fallback. Runs as `prebuild`, so it never
// fails the build: without a key or a reachable cloud it keeps a valid
// previous file or writes `null` (the app then serves control until its
// first fetch).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { parseSecretKey, verifyBundle } from "@next-evolve/protocol";
import { trustedKeys } from "../core/keys";
import { fetchBundle } from "../store/fetch";
import { DEFAULT_CLOUD_URL } from "../store/runtime";

type Env = Record<string, string | undefined>;

export const BUILD_BUNDLE_PATH = ".evolve/bundle.generated.ts";

export type PullDeps = {
  env: Env;
  cwd?: string;
  out?: (s: string) => void;
  err?: (s: string) => void;
};

const HEADER = "// Generated by next-evolve pull. Do not edit; do not commit.\n";
export const renderBuildBundle = (token: string | null): string =>
  `${HEADER}const bundle: string | null = ${JSON.stringify(token)};\nexport default bundle;\n`;

/** The token inside a generated module, or null. */
export function readBuildBundle(source: string): string | null {
  const m = /const bundle: string \| null = ("[A-Za-z0-9_.-]+");/.exec(source);
  return m ? (JSON.parse(m[1]!) as string) : null;
}

export async function pullCommand(_args: string[], deps: PullDeps): Promise<number> {
  const { env } = deps;
  const out = deps.out ?? ((s) => console.warn(s));
  const err = deps.err ?? ((s) => console.error(s));
  const file = join(deps.cwd ?? process.cwd(), BUILD_BUNDLE_PATH);
  mkdirSync(dirname(file), { recursive: true });

  const key = env.EVOLVE_SECRET_KEY;
  const site = parseSecretKey(key ?? "")?.siteId;
  const keys = trustedKeys(env);
  const now = Math.floor(Date.now() / 1000);
  const valid = (token: string | null) =>
    token && site ? verifyBundle(token, { keys, site, now }) : null;

  let current: string | null = null;
  try {
    current = readFileSync(file, "utf8");
  } catch {}
  const previous = current === null ? null : readBuildBundle(current);
  // Same content → no write (a re-run of init changes nothing on disk).
  const write = (token: string | null) => {
    const next = renderBuildBundle(token);
    if (next !== current) writeFileSync(file, next);
  };
  const keep = (why: string) => {
    const prev = valid(previous);
    const token = prev?.ok ? previous : null;
    write(token);
    err(
      `next-evolve pull: ${why}; ${token ? "kept the previous bundle" : "wrote an empty build bundle (control until the first fetch)"}`,
    );
    return 0;
  };

  if (!key || !site) return keep("EVOLVE_SECRET_KEY is not set");
  const cloudUrl = env.EVOLVE_CLOUD_URL ?? DEFAULT_CLOUD_URL;
  if (!cloudUrl) return keep("no cloud URL");
  const res = await fetchBundle({ cloudUrl, secretKey: key, timeoutMs: 10_000 });
  if (res.status === "error") return keep(`bundle fetch failed (${res.code})`);
  if (res.status !== "ok") return keep("unexpected 304");
  const v = valid(res.token);
  if (!v?.ok) return keep(`bundle rejected (${v?.reason ?? "invalid"})`);
  write(res.token);
  out(`next-evolve pull: wrote ${BUILD_BUNDLE_PATH} (ver ${v.payload.ver})`);
  return 0;
}
