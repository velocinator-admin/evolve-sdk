import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  type FakeCloud,
  startFakeCloud,
  TEST_PUBLIC_KEY_ENV,
  TEST_SECRET_KEY,
  TEST_SITE,
} from "@next-evolve/fake-cloud";
import { createKeyRing } from "@next-evolve/protocol";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createMemoryStore } from "../store/memory";
import { BUILD_BUNDLE_PATH, pullCommand, readBuildBundle } from "./pull";

let cloud: FakeCloud;
beforeAll(async () => {
  cloud = await startFakeCloud();
});
afterAll(() => cloud.close());

const content = { routing: { routes: { "/": [] }, experiments: {} }, variants: {} };
const env = (o: Record<string, string | undefined> = {}) => ({
  EVOLVE_SECRET_KEY: TEST_SECRET_KEY,
  EVOLVE_CLOUD_URL: cloud.url,
  EVOLVE_UNSAFE_TEST_PUBLIC_KEY: TEST_PUBLIC_KEY_ENV,
  NODE_ENV: "test",
  ...o,
});

function run(cwd: string, e: Record<string, string | undefined>) {
  const lines: string[] = [];
  return pullCommand([], {
    env: e,
    cwd,
    out: (s) => lines.push(s),
    err: (s) => lines.push(s),
  }).then((code) => ({ code, lines, file: readFileSync(join(cwd, BUILD_BUNDLE_PATH), "utf8") }));
}

describe("next-evolve pull (build-time bundle)", () => {
  it("writes the verified bundle as a TS module; a fresh instance offline serves it", async () => {
    const dir = mkdtempSync(join(tmpdir(), "evolve-pull-"));
    const { token, payload } = cloud.publish({ site: TEST_SITE, ...content });
    const r = await run(dir, env());
    expect(r.code).toBe(0);
    expect(r.file).toContain("Generated by next-evolve pull");
    expect(readBuildBundle(r.file)).toBe(token);

    const store = createMemoryStore({
      site: TEST_SITE,
      keys: createKeyRing({ "fake-cloud-test": cloud.key.publicKey }),
      pollMs: 60_000,
      initialToken: readBuildBundle(r.file),
      fetcher: async () => ({ status: "error", code: "network" }),
    });
    expect(store.peek()?.ver).toBe(payload.ver);
  });

  it("never fails the build: no key or cloud down → null module (or keeps a valid previous one)", async () => {
    const dir = mkdtempSync(join(tmpdir(), "evolve-pull-"));
    const none = await run(dir, env({ EVOLVE_SECRET_KEY: undefined }));
    expect(none.code).toBe(0);
    expect(readBuildBundle(none.file)).toBeNull();
    expect(none.lines.join("\n")).toMatch(/EVOLVE_SECRET_KEY/);

    cloud.publish({ site: TEST_SITE, ...content });
    const ok = await run(dir, env());
    const down = await run(dir, env({ EVOLVE_CLOUD_URL: "http://127.0.0.1:1" }));
    expect(down.code).toBe(0);
    expect(readBuildBundle(down.file)).toBe(readBuildBundle(ok.file));
  });

  it("refuses a bundle that doesn't verify (wrong key) and writes null", async () => {
    const dir = mkdtempSync(join(tmpdir(), "evolve-pull-"));
    cloud.publish({ site: TEST_SITE, ...content });
    const r = await run(dir, env({ EVOLVE_UNSAFE_TEST_PUBLIC_KEY: undefined }));
    expect(r.code).toBe(0);
    expect(readBuildBundle(r.file)).toBeNull();
    expect(r.lines.join("\n")).toMatch(/rejected/);
  });

  it("ignores a garbage existing file", async () => {
    const dir = mkdtempSync(join(tmpdir(), "evolve-pull-"));
    const { mkdirSync } = await import("node:fs");
    mkdirSync(join(dir, ".evolve"));
    writeFileSync(join(dir, BUILD_BUNDLE_PATH), "nonsense");
    const r = await run(dir, env({ EVOLVE_CLOUD_URL: "http://127.0.0.1:1" }));
    expect(readBuildBundle(r.file)).toBeNull();
  });
});
